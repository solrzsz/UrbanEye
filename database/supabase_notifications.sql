-- Database migration: persistent report-status notifications.
-- Run after supabase_sql_politicas.txt. Safe to run more than once.

alter table public.profiles
  add column if not exists notifications_enabled boolean not null default true;

grant update (notifications_enabled) on public.profiles to authenticated;

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  report_id bigint references public.reports(id) on delete cascade,
  title text not null,
  message text not null,
  created_at timestamptz not null default now(),
  read_at timestamptz
);

alter table public.notifications enable row level security;

revoke all on public.notifications from anon, authenticated;
grant select on public.notifications to authenticated;
grant update (read_at) on public.notifications to authenticated;

drop policy if exists "Usuário pode ler suas notificações" on public.notifications;
create policy "Usuário pode ler suas notificações"
on public.notifications
for select
to authenticated
using (auth.uid() = user_id);

drop policy if exists "Usuário pode marcar suas notificações como lidas" on public.notifications;
create policy "Usuário pode marcar suas notificações como lidas"
on public.notifications
for update
to authenticated
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

create or replace function public.notify_report_status_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  should_notify boolean;
begin
  if new.status is not distinct from old.status or new.user_id is null then
    return new;
  end if;

  select coalesce(
    (select p.notifications_enabled from public.profiles p where p.id = new.user_id),
    true
  )
  into should_notify;

  if should_notify then
    insert into public.notifications (user_id, report_id, title, message)
    values (
      new.user_id,
      new.id,
      'Atualização do relato',
      format('O status do seu relato "%s" mudou para "%s".', coalesce(new.category, 'Relato'), coalesce(new.status, 'indisponível'))
    );
  end if;

  return new;
end;
$$;

drop trigger if exists on_report_status_changed on public.reports;
create trigger on_report_status_changed
after update of status on public.reports
for each row
execute procedure public.notify_report_status_change();

revoke all on function public.notify_report_status_change() from public;
